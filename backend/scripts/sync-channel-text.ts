/**
 * Copies the app's wording for KYC problems, documents, consent, results, payment blocks and order
 * stages into backend/src/channels/sharedText.ts, so WhatsApp messages say exactly what the app
 * says. Run after changing those strings in frontend/src/i18n:
 *   cd backend; npx tsx scripts/sync-channel-text.ts; cd ..
 * frontend/src/i18n/channelText.test.ts fails when the two drift apart.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { en } from "../../frontend/src/i18n/en.js";
import { hi } from "../../frontend/src/i18n/hi.js";
import { SHARED_PREFIXES } from "../src/channels/sharedKeys.js";

const keys = Object.keys(en).filter((k) => SHARED_PREFIXES.some((p) => k.startsWith(p)));
const pick = (dict: Record<string, string>) => Object.fromEntries(keys.map((k) => [k, dict[k]!]));
const out = `// GENERATED by backend/scripts/sync-channel-text.ts from frontend/src/i18n (do not edit by hand).
export const SHARED_TEXT = ${JSON.stringify({ en: pick(en), hi: pick(hi) }, null, 2)} as const;
`;
writeFileSync(resolve(import.meta.dirname, "..", "src", "channels", "sharedText.ts"), out, "utf8");
console.log(`${keys.length} keys written`);
