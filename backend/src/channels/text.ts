export type OwnKey = keyof (typeof OWN)["en"];
export type SharedKey = keyof (typeof SHARED_TEXT)["en"];
export type ChannelKey = OwnKey | SharedKey;
export type Vars = Record<string, string | number>;

export function wa(lang: Lang, key: ChannelKey, vars: Vars = {}): string {
  const own = OWN[lang] as Record<string, string>;
  const shared = SHARED_TEXT[lang] as Record<string, string>;
  const template = own[key] ?? shared[key];
  if (template === undefined) throw new Error(`Missing WhatsApp text ${key}`);
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export const hasText = (lang: Lang, key: string): key is ChannelKey => key in OWN[lang] || key in SHARED_TEXT[lang];
export const OWN_TEXT = OWN;

const inr = new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 });
/** Same formats as the app (frontend/src/format.ts). */
export const formatInr = (amount: number) => inr.format(amount);
export function formatDate(isoDate: string, lang: Lang): string {
  return new Date(`${isoDate}T00:00:00Z`).toLocaleDateString(lang === "hi" ? "hi-IN" : "en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
    numberingSystem: "latn",
  });
}
